def naf(k):
    """Signed digits of k, most significant first, no two adjacent non-zero."""
    d = []
    while k:
        z = (2 - k % 4) if k & 1 else 0
        k = (k - z) // 2
        d.append(z)
    return d[::-1]


def naf_array(name, k, comment):
    """k's signed digits, most significant first: the non-adjacent form when it has fewer non-zero
    digits than binary, binary otherwise (a NAF can be one digit longer, costing a squaring)."""
    d = naf(k)
    if sum(1 for z in d if z) >= bin(k).count("1"):
        d = [int(c) for c in bin(k)[2:]]
    body = ", ".join(str(z) for z in d)
    return [f"/* {comment} Signed digits, most significant first. */",
            f"#define {name}_LEN {len(d)}", f"static const int8_t {name}[{len(d)}] = {{{body}}};"]


def limbs(v, n):
    assert 0 <= v < 1 << (64 * n)
    return "{" + ", ".join(f"0x{(v >> (64 * i)) & (2**64 - 1):016x}ULL" for i in range(n)) + "}"


def fp(name, v, n, comment=None):
    out = [f"/* {comment} */"] if comment else []
    return out + [f"static const fp {name} = {{{limbs(v, n)}}};"]


def fp2(v, n):
    return f"{{{{{limbs(v[0], n)}}}, {{{limbs(v[1], n)}}}}}"


def fp2c(name, v, n, comment=None):
    out = [f"/* {comment} */"] if comment else []
    return out + [f"static const fp2 {name} = {fp2(v, n)};"]


def header(c, n, extra):
    lines = [
        "/* SPDX-FileCopyrightText: 2026 Demerzel Solutions Limited",
        " * SPDX-License-Identifier: MIT",
        " *",
        f" * {c.name} constants for the pairing code. Generated by gen_constants.py from model.py; do not edit. */",
        "",
        f"#define X_ABS 0x{abs(c.x):016x}ULL",
        f"#define X_NEGATIVE {1 if c.x < 0 else 0}",
        "",
    ]
    lines += naf_array("LOOP_NAF", c.loop_count, "Miller loop scalar (6x + 2 for BN, |x| for BLS12).")
    lines += naf_array("X_NAF", abs(c.x), "|x|.")
    lines += fp("FIELD_P", c.p, n)
    lines += fp("P_MINUS_2", c.p - 2, n, "Exponent of the inverse by exponentiation.")
    lines += fp("INV2", (c.p + 1) // 2, n)
    lines += fp("CURVE_B", c.b, n)
    lines += fp2c("XI", c.xi, n, "Fp6 = Fp2[v]/(v^3 - XI), Fp12 = Fp6[w]/(w^2 - v).")
    lines += fp2c("TWIST_B", c.b2, n, "b' of the twist E': y^2 = x^3 + b'.")
    lines += fp2c("TWIST_B3", c.f2scale(c.b2, 3), n)
    lines += fp2c("PI_X", c.pi_x, n, "Twisted Frobenius on E': (x, y) -> (conj(x) PI_X, conj(y) PI_Y).")
    lines += fp2c("PI_Y", c.pi_y, n)
    lines += ["/* Frobenius on Fp12: coefficient k of w is scaled by GAMMA[n - 1][k] = XI^(k (p^n - 1) / 6). */",
              "static const fp2 GAMMA[3][6] = {"]
    for i in range(1, 4):
        lines.append("    {" + ",\n     ".join(fp2(c.gamma[i][k], n) for k in range(6)) + "},")
    lines.append("};")
    return "\n".join(lines + [""] + extra + [""])


def bn254():
    c, n = BN254, 4
    c.loop_count = 6 * c.x + 2
    extra = naf_array("SIX_X2_NAF", 6 * c.x * c.x, "6x^2, the G2 membership scalar.")
    return header(c, n, extra)


def bls12_381():
    c, n = BLS12_381, 6
    c.loop_count = abs(c.x)
    r = c.r
    extra = []
    extra += [f"static const uint64_t ORDER_R[4] = {limbs(r, 4)};"]
    extra += fp("SQRT_EXPONENT", (c.p + 1) // 4, n, "(p + 1) / 4: p = 3 mod 4.")
    extra += fp("HALF_P", (c.p - 1) // 2, n, "y is the larger root when y > (p - 1) / 2.")
    extra += fp("BETA", c.beta, n, "(x, y) -> (BETA x, y) is [-x^2] on G1.")
    extra += fp("G1_X", c.G1[0], n)
    extra += fp("G1_Y", c.G1[1], n)
    extra += fp2c("G2_X", BLS_G2[0], n)
    extra += fp2c("G2_Y", BLS_G2[1], n)
    extra += fp2c("S_G2_X", S_G2[0], n, "[s]G2 from the KZG trusted setup.")
    extra += fp2c("S_G2_Y", S_G2[1], n)
    for q in (BLS_G2, S_G2):
        assert c.on_twist(q) and c.twist_mul(c.r, q) is None
    return header(c, n, extra)


def main():
    outputs = {"bn254_constants.h": bn254(), "bls12_381_constants.h": bls12_381()}
    check = "--check" in sys.argv
    stale = []
    for name, text in outputs.items():
        path = HERE / name
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
    if stale:
        sys.exit(f"stale: {', '.join(stale)}; run gen_constants.py")


if __name__ == "__main__":
    main()
